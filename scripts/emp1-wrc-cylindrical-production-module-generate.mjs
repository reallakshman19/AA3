#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const packagePath=resolve(process.argv[2]??'test-results/emp1-cylindrical-production-package.json');
const outputPath=resolve(process.argv[3]??'src/core/emp1/emp1-wrc537-cylindrical-data.generated.js');
const pkg=JSON.parse(await readFile(packagePath,'utf8'));
if(pkg.schema!=='emp1-wrc537-cylindrical-production-package/v1') throw new Error('EMP1_WRC_PRODUCTION_MODULE_PACKAGE_SCHEMA');
if(pkg.counts?.curves!==321||pkg.counts?.scalarCoefficients!==3210) throw new Error('EMP1_WRC_PRODUCTION_MODULE_PACKAGE_CARDINALITY');
if(!/^[a-f0-9]{64}$/u.test(pkg.datasetHash??'')) throw new Error('EMP1_WRC_PRODUCTION_MODULE_DATASET_HASH');
const rows=pkg.semanticPayload.curves;
const lines=[
  '// Generated by scripts/emp1-wrc-cylindrical-production-module-generate.mjs. Do not edit manually.\n',
  `export const EMP1_WRC537_CYL_DATASET_HASH=${JSON.stringify(pkg.datasetHash)};\n`,
  `export const EMP1_WRC537_CYL_SOURCE_SHA256=${JSON.stringify(pkg.sourceDocumentSha256)};\n`,
  "export const EMP1_WRC537_CYL_COEFFICIENT_ORDER=Object.freeze(['a','b','c','d','e','f','g','h','i','j']);\n",
  'export const EMP1_WRC537_CYL_CURVES=Object.freeze([\n',
];
for(const row of rows){
  lines.push(`  ${JSON.stringify([row.figure,row.variant==='ORIGINAL'?'O':'E',row.gamma,row.pdfPage,...row.coefficients])},\n`);
}
lines.push(']);\n');
lines.push(`export const EMP1_WRC537_CYL_EXCLUDED=Object.freeze(${JSON.stringify(pkg.excludedSourceRows.map((row)=>[row.figure,row.variant==='ORIGINAL'?'O':'E',row.gamma,row.pdfPage,row.reason]))});\n`);
lines.push(`export const EMP1_WRC537_CYL_PACKAGE_COUNTS=Object.freeze(${JSON.stringify(pkg.counts)});\n`);
await mkdir(dirname(outputPath),{recursive:true});
await writeFile(outputPath,lines.join(''),'utf8');
console.log(JSON.stringify({schema:'emp1-wrc537-cylindrical-production-module-generation/v1',status:'PASS',outputPath,datasetHash:pkg.datasetHash,curves:rows.length},null,2));
