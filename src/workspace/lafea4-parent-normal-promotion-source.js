import {
  LAFEA4_PARENT_NORMAL_AUTHORIZED_STATUS,
  validateLafea4ParentNormalActivationRecord,
} from './lafea4-parent-normal-activation-record.js';
import {
  LAFEA4_PARENT_NORMAL_PRODUCTION_ACTIVATION_POLICY,
} from './lafea4-parent-normal-production-activation.js';

export const LAFEA4_PARENT_NORMAL_PROMOTION_SOURCE_SCHEMA =
  'lafea4-parent-normal-promotion-source/v1';
export const LAFEA4_PARENT_NORMAL_PRODUCTION_TRUST_ROOT_PATH =
  'src/workspace/lafea4-parent-normal-production-activation.js';

/**
 * Deterministically render the only production source file a future promotion
 * is allowed to replace. This is tooling, not runtime authority: the caller
 * must still prove the record against the exact TECH-8 evidence bundle before
 * this source may be written to the repository.
 */
export function renderLafea4ParentNormalProductionActivationSource(value) {
  const record = validateLafea4ParentNormalActivationRecord(value);
  if (record.status !== LAFEA4_PARENT_NORMAL_AUTHORIZED_STATUS) {
    fail('LAFEA4_PARENT_NORMAL_PROMOTION_RECORD_NOT_AUTHORIZED');
  }
  const json = JSON.stringify(record, null, 2);
  return `${header()}\nconst ACTIVATION_RECORD = ${json};\n\n`
    + 'export const LAFEA4_PARENT_NORMAL_PRODUCTION_ACTIVATION_RECORD =\n'
    + '  deepFreeze(ACTIVATION_RECORD);\n\n'
    + 'export const LAFEA4_PARENT_NORMAL_PRODUCTION_ACTIVATION_POLICY =\n'
    + `  '${LAFEA4_PARENT_NORMAL_PRODUCTION_ACTIVATION_POLICY}';\n\n`
    + 'function deepFreeze(value) {\n'
    + "  if (!value || typeof value !== 'object' || Object.isFrozen(value)) return value;\n"
    + '  Object.values(value).forEach(deepFreeze);\n'
    + '  return Object.freeze(value);\n'
    + '}\n';
}

export function validateLafea4ParentNormalPromotionRecordForHead(value, expectedHead) {
  const record = validateLafea4ParentNormalActivationRecord(value);
  if (record.status !== LAFEA4_PARENT_NORMAL_AUTHORIZED_STATUS) {
    fail('LAFEA4_PARENT_NORMAL_PROMOTION_RECORD_NOT_AUTHORIZED');
  }
  if (typeof expectedHead !== 'string' || !/^[0-9a-f]{40}$/u.test(expectedHead)) {
    fail('LAFEA4_PARENT_NORMAL_PROMOTION_EXPECTED_HEAD_INVALID');
  }
  if (record.expectedHead !== expectedHead) {
    fail('LAFEA4_PARENT_NORMAL_PROMOTION_RECORD_HEAD_MISMATCH');
  }
  return record;
}

function header() {
  return `/**
 * Code-owned production trust root for the LAFEA.4 parent-normal hard gate.
 *
 * GENERATED BY TECH-12F FROM AN EXACT-HEAD TECH-8 PASS BUNDLE AND THE EXACT
 * RECONSTRUCTED TECH-12D AUTHORIZATION RECORD. DO NOT HAND-EDIT THIS RECORD.
 * The promotion review must contain no tracked production change other than
 * this trust-root source file.
 */`;
}
function fail(code) { const error = new TypeError(code); error.code = code; throw error; }
